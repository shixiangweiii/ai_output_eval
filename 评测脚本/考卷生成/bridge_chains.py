def render_chain_document(spec: Dict[str, Any]) -> str:
    """把一份链路文档规格渲染成 Markdown。

    布局：每节承载一条事实的 home 陈述与另一条事实的 xref 陈述，中间垫入两段填充，
    保证不同事实的 span 拉开 300 字以上，避免一个检索块同时命中多题。
    """
    facts = spec["facts"]
    # 填充段落带上本文档自己的主体名：既让行文更像真实文书，也避免各文档共用同一批
    # 措辞而产生虚假的字面相似——那会把桥接文档误拉进题面的检索结果里（G13 会拦）。
    subject = spec.get("entity") or spec["links"][0]
    prose = [paragraph.format(subject=subject) for paragraph in spec["prose"]]
    lines = [f"# {spec['title']}", "", spec["header"], ""]
    for index, section in enumerate(spec["sections"]):
        lines.extend([f"## {section}", ""])
        if index >= len(facts):  # 末节只放反捷径提示
            lines.extend([spec["caveat"], "", prose[(index * 3 + 1) % len(prose)], ""])
            continue
        home = facts[index]
        xref = facts[index - 1]
        size = len(prose)
        lines.extend([
            home["home"] + "。", "",
            prose[(index * 3) % size], "",
            prose[(index * 3 + 1) % size], "",
            prose[(index * 5 + 4) % size], "",
            prose[(index * 7 + 6) % size], "",
            f"本节关于{subject}的表述以文首标注的编号和日期为准。若在其他材料中见到不同版本，"
            "请先核对编号再决定采信哪一份，不要凭标题相似度判断。", "",
            xref["xref"] + "。", "",
            prose[(index * 3 + 2) % size], "",
            prose[(index * 5 + 7) % size], "",
            prose[(index * 7 + 3) % size], "",
            prose[(index * 9 + 5) % size], "",
            f"以上关于{subject}的内容如与后续正式文件存在出入，以正式文件为准，并按流程反馈至"
            "本文件的发布部门统一更正，不得在转述环节自行调整表述。", "",
        ])
    return "\n".join(lines).rstrip() + "\n"


def build_chain_fact_entries(spec: Dict[str, Any], chain: Dict[str, Any]) -> List[Dict[str, Any]]:
    """产出链路文档的台账 facts 段；locator 由同一套模板确定性推导。"""
    entries = []
    for index, fact in enumerate(spec["facts"]):
        home_section = spec["sections"][index]
        xref_section = spec["sections"][(index + 1) % len(spec["sections"])]
        entries.append({
            "fact_id": fact["fact_id"],
            "family": chain["family"],
            "cluster_id": chain["cluster_id"],
            "chain_id": chain["chain_id"],
            # 假桥接文档不属于任何链路，它的证据只能当作 supporting / 负例使用
            "hop_role": spec.get("role", "supporting"),
            "kind": "text",
            "claim_type": "anchor" if index % 2 == 0 else "passage",
            "dimension": f"{spec['title']}·{home_section}",
            "values": {spec["doc"]: fact["value"]},
            "locations": {spec["doc"]: [
                {"section": home_section, "locator": fact["home"]},
                {"section": xref_section, "locator": fact["xref"]},
            ]},
        })
    return entries
