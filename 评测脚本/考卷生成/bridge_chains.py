def _endpoint(doc, title, header, entity, link, sections, facts, caveat, prose):
    return {
        "doc": doc, "title": title, "header": header, "role": "endpoint",
        "entity": entity, "links": [link], "sections": sections,
        "facts": facts, "caveat": caveat, "prose": prose,
    }


def _bridge(doc, title, header, links, sections, facts, caveat, prose):
    return {
        "doc": doc, "title": title, "header": header, "role": "bridge",
        "entity": None, "links": links, "sections": sections,
        "facts": facts, "caveat": caveat, "prose": prose,
    }


def _f(fact_id, value, home, xref):
    return {"fact_id": fact_id, "value": value, "home": home, "xref": xref}


